"""Generate a design's software contract: ``naiad.h``, ``linker.ld``, ``crt0.S``, ``naiad.mk``.

Everything a C program needs to know about a design comes from here, so the
design file stays the single source of truth for addresses and the ISA. Each
file carries a do-not-edit banner naming the design it was generated from.

The crt0 and linker script handle both XLENs: RV64 uses ``ld``/``sd`` and the
same 8-byte ``.bss`` alignment as RV32, so only the core factory changes when the
RV64 core arrives.

**Multi-hart designs** (``cores.count > 1``; a single-hart design's files are
exactly what they were) follow one convention, which the same ELF also gets on
``spike -p<n>``:

* Every hart starts at ``_start``, reads ``mhartid`` and takes its own stack:
  hart ``h``'s top is ``_stack_top - h * STACK_SIZE``; the linker script keeps
  ``NAIAD_HARTS * STACK_SIZE`` free below the top of program memory. There is
  no TLS (``.tdata``/``.tbss`` are not supported). Each hart turns its own FP /
  vector unit on (``mstatus`` is per hart).
* Hart 0 zeroes ``.bss`` and then releases the others by setting their CLINT
  ``msip``; until then they sleep in ``wfi`` with ``mie.MSIE`` set (no trap:
  ``mstatus.MIE`` stays clear), and each clears its ``msip`` and ``mie`` on the
  way out. A hart whose ``mhartid`` is ``NAIAD_HARTS`` or more parks for good.
* **Every hart calls ``main``.** Kernels split work with ``naiad_hartid()`` and
  ``NAIAD_HARTS`` and synchronise with ``naiad_barrier()``
  (``naiad_platform.h``).
* **Hart 0's return from ``main`` is the program's exit**; another hart that
  returns parks in ``wfi`` for good. ``naiad_exit()`` from any hart ends the run
  at once (the HTIF honours the first exit command it sees).
"""

import re
from pathlib import Path

from framework.naiad.registry import IP_REGISTRY


def _banner(design, comment):
    source = design.path or design.name
    lines = [
        f"Generated by framework.naiad.gen from {Path(source).name} (design '{design.name}').",
        "DO NOT EDIT: regenerate from the design file instead.",
    ]
    if comment == "#":
        return "".join(f"# {line}\n" for line in lines)
    return "/*\n" + "".join(f" * {line}\n" for line in lines) + " */\n"


def _ident(name):
    return re.sub(r"[^A-Za-z0-9]", "_", name).upper()


def _hex(value):
    suffix = "ULL" if value > 0xFFFFFFFF else "UL"
    return f"0x{value:08X}{suffix}"


def _block_defines(design):
    """``(name, value)`` defines per block: base, size, window, plus the IP's own."""
    out = []
    for spec in design.blocks:
        prefix = f"NAIAD_{_ident(spec.name)}"
        out.append((None, f"{spec.name}: {spec.type}"))
        if spec.base is not None:
            out += [
                (f"{prefix}_BASE", _hex(spec.base)),
                (f"{prefix}_SIZE", _hex(spec.size)),
                (f"{prefix}_WINDOW", _hex(spec.window)),
            ]
        block = IP_REGISTRY[spec.type](spec)
        for name, value in block.header_defines():
            out.append(
                (f"{prefix}_{name}", _hex(value) if isinstance(value, int) else value)
            )
    return out


def _matrix_defines(spec):
    """The matrix unit's shape, formats and features, then the encodings table."""
    if spec.mode == "ime":
        from framework.matrix.ime import header_lines

        return header_lines(spec)
    if spec.mode == "vme":
        from framework.matrix.vme import header_lines as vme_header_lines

        return vme_header_lines(spec)
    from framework.matrix.encodings import TABLE, header_defines

    lines = [
        "",
        f"/* matrix unit: {spec.mode}, one per hart */",
        "#define NAIAD_HAS_MATRIX 1",
        f"#define NAIAD_MATRIX_{_ident(spec.mode)} 1",
        f'#define NAIAD_MATRIX_MODE "{spec.mode}"',
    ]
    for name in ("m", "n", "k", "tiles", "accs"):
        lines.append(f"#define NAIAD_MATRIX_{name.upper()} {getattr(spec, name)}")
    lines += [f"#define NAIAD_MATRIX_IN_{_ident(f)} 1" for f in spec.in_formats]
    lines += [f"#define NAIAD_MATRIX_ACC_{_ident(f)} 1" for f in spec.acc_formats]
    lines += [f"#define NAIAD_MATRIX_FEATURE_{_ident(f)} 1" for f in spec.features]
    if spec.acc_mem:
        lines.append("#define NAIAD_MATRIX_FEATURE_ACC_MEM 1")
    if spec.profile is not None:
        lines.append(f"#define NAIAD_MATRIX_PROFILE_{_ident(spec.profile)} 1")
    lines += ["", "/* matrix encodings (framework/matrix/encodings.yaml) */"]
    lines += [f"#define {name} {value:#x}" for name, value in header_defines(TABLE)]
    return lines


def _counter_defines(design):
    """Counter events a kernel can read with ``naiad_counter(EVENT)`` (``naiad_platform.h``).

    ``NAIAD_HPM_<EVENT>`` is the Zihpm counter a design binds the event to, and
    ``NAIAD_PERFOFF_<EVENT>`` its offset in the first perfcounters block (the
    one ``NAIAD_PERF_ADDR`` names). ``NAIAD_COUNTER_<EVENT>`` packs both as
    ``hpm, offset`` (0 / -1 when absent) for every event either one names.
    """
    hpm = {event: n for n, event in design.counters.hpm}
    perf = design.blocks_of_type("perfcounters")
    offsets = {}
    if perf:
        names = IP_REGISTRY["perfcounters"](perf[0]).required_events()
        offsets = {name: 8 * i for i, name in enumerate(names)}
    if not hpm and not offsets:
        return []
    lines = [
        "",
        "/* counter events: read with naiad_counter(EVENT) from naiad_platform.h */",
    ]
    if hpm:
        lines.append("#define NAIAD_HAS_HPM 1")
    # Keyed by identifier, so a legacy flat name (matrix_macs) and its dotted
    # form (matrix.macs) share one set of defines.
    events = {}
    for event in [*hpm, *offsets]:
        events.setdefault(_ident(event), []).append(event)
    for ident, names in events.items():
        n = next((hpm[e] for e in names if e in hpm), None)
        off = next((offsets[e] for e in names if e in offsets), None)
        lines.append(f"/* {' / '.join(dict.fromkeys(names))} */")
        if n is not None:
            lines.append(f"#define NAIAD_HPM_{ident} {n}")
        if off is not None:
            lines.append(f"#define NAIAD_PERFOFF_{ident} {off:#x}")
        lines.append(
            f"#define NAIAD_COUNTER_{ident} {0 if n is None else n}, {-1 if off is None else hex(off)}"
        )
    return lines


def gen_header(design):
    cores = design.cores
    lines = [_banner(design, "/*"), "#ifndef NAIAD_H", "#define NAIAD_H", ""]
    lines += [
        f'#define NAIAD_DESIGN "{design.name}"',
        f"#define NAIAD_XLEN {cores.xlen}",
        f"#define NAIAD_NUM_CORES {cores.count}",
        f'#define NAIAD_MARCH "{cores.march}"',
    ]
    lines += [f"#define NAIAD_ISA_{_ident(ext)} 1" for ext in cores.isa]
    if cores.has_vector:
        lines += [
            f"#define NAIAD_VLEN {cores.vlen}",
            f"#define NAIAD_ELEN {cores.elen}",
        ]
    prog = design.program_memory
    lines += [
        f"#define NAIAD_PROGRAM_MEMORY NAIAD_{_ident(prog.name)}_BASE",
        f"#define NAIAD_STACK_SIZE {_hex(design.program.stack_size)}",
    ]
    if cores.count > 1:
        lines += [
            "/* multi-hart: every hart runs main (see naiad_platform.h, naiad_hartid / naiad_barrier) */",
            "#define NAIAD_MULTICORE 1",
            f"#define NAIAD_HARTS {cores.count}",
        ]
    # The first block of each type the platform header uses, under a name-independent alias.
    for type_name, alias in (
        ("clint", "CLINT"),
        ("perfcounters", "PERF"),
        ("htif", "HTIF"),
        ("dma", "DMA"),
    ):
        found = design.blocks_of_type(type_name)
        if found:
            lines.append(f"#define NAIAD_HAS_{alias} 1")
            if found[0].base is not None:
                lines.append(
                    f"#define NAIAD_{alias}_ADDR NAIAD_{_ident(found[0].name)}_BASE"
                )
    for name, value in _block_defines(design):
        if name is None:
            lines += ["", f"/* {value} */"]
        else:
            lines.append(f"#define {name} {value}")
    if design.matrix is not None:
        lines += _matrix_defines(design.matrix)
    lines += _counter_defines(design)
    lines += ["", "#endif /* NAIAD_H */", ""]
    return "\n".join(lines)


def gen_linker(design):
    prog = design.program_memory
    harts = design.cores.count
    # One stack per hart, hart h's top at _stack_top - h * STACK_SIZE (crt0).
    stacks = "STACK_SIZE" if harts == 1 else "NAIAD_HARTS * STACK_SIZE"
    harts_line = "" if harts == 1 else f"NAIAD_HARTS = {harts};\n"
    return f"""{_banner(design, "/*")}
OUTPUT_ARCH("riscv")
ENTRY(_start)

STACK_SIZE = {hex(design.program.stack_size)};
{harts_line}
MEMORY
{{
  RAM (rwx) : ORIGIN = {hex(prog.base)}, LENGTH = {hex(prog.size)}
}}

SECTIONS
{{
  .text : {{
    KEEP(*(.text.init))
    *(.text .text.*)
  }} > RAM

  .rodata : ALIGN(8) {{
    *(.rodata .rodata.*)
    *(.srodata .srodata.*)
  }} > RAM

  /* tohost/fromhost: before .data so no NOBITS section precedes a PROGBITS one. */
  .tohost : ALIGN(64) {{
    KEEP(*(.tohost))
  }} > RAM

  .data : ALIGN(8) {{
    *(.data .data.*)
  }} > RAM

  .sdata : ALIGN(8) {{
    __global_pointer$ = . + 0x800;
    *(.sdata .sdata.*)
  }} > RAM

  .bss : ALIGN(8) {{
    __bss_start = .;
    *(.sbss .sbss.*)
    *(.bss .bss.*)
    *(COMMON)
    . = ALIGN(8);
    __bss_end = .;
  }} > RAM

  /* Host-written kernel I/O (NAIAD_IO): not zeroed by crt0, so arrays the host
     writes after loading the ELF (framework.naiad.kernel_io) survive start-up. */
  .noinit (NOLOAD) : ALIGN(64) {{
    *(.noinit .noinit.*)
  }} > RAM

  . = ALIGN(16);
  _end = .;
  __heap_start = .;

  _stack_top = ORIGIN(RAM) + LENGTH(RAM);
  _stack_bottom = _stack_top - {stacks};
  ASSERT(_end <= _stack_bottom, "program overlaps the stack{"s" if harts > 1 else ""}")
}}
"""


def gen_crt0(design):
    xlen = design.cores.xlen
    store, regbytes = ("sd", 8) if xlen == 64 else ("sw", 4)
    # Wait for the host to consume the previous command (a console byte main may
    # have just sent) before ringing the doorbell again: Spike polls tohost only
    # every few thousand instructions, so an unconditional store would overwrite it.
    if xlen == 64:
        wait_idle = "4:\n  ld    t1, 0(t0)\n  bnez  t1, 4b"
        exit_store = "  sd    a0, 0(t0)"
    else:
        wait_idle = "4:\n  lw    t1, 0(t0)\n  lw    t2, 4(t0)\n  or    t1, t1, t2\n  bnez  t1, 4b"
        # RV32: high word first, low word last; the low-word store is the HTIF doorbell.
        exit_store = "  sw    zero, 4(t0)\n  sw    a0, 0(t0)"
    # FP instructions trap while mstatus.FS is Off (Spike, hardware), so an FP
    # design's crt0 turns the unit on (FS = Initial) before any C code runs.
    isa = design.cores.isa
    if ("f" in isa or "d" in isa) and "zicsr" in isa:
        fp_on = "  /* mstatus.FS = Initial, so FP instructions do not trap. */\n  li    t0, 1 << 13\n  csrs  mstatus, t0\n"
    else:
        fp_on = ""
    # Vector instructions trap the same way while mstatus.VS is Off.
    if design.cores.has_vector and "zicsr" in isa:
        fp_on += "  /* mstatus.VS = Initial, so vector instructions do not trap. */\n  li    t0, 1 << 9\n  csrs  mstatus, t0\n"
    if design.cores.count > 1:
        return _gen_crt0_multicore(design, fp_on, wait_idle, exit_store)
    return f"""{_banner(design, "/*")}
  .section .text.init, "ax", @progbits
  .globl _start
_start:
  .option push
  .option norelax
  la    gp, __global_pointer$
  .option pop
  la    sp, _stack_top

  /* Zero .bss ({regbytes}-byte stores; the linker script aligns both ends to 8). */
  la    t0, __bss_start
  la    t1, __bss_end
1:
  bgeu  t0, t1, 2f
  {store}    zero, 0(t0)
  addi  t0, t0, {regbytes}
  j     1b
2:
{fp_on}  li    a0, 0
  li    a1, 0
  call  main

  /* exit(main's return): tohost = (code << 1) | 1. */
  .globl _exit
_exit:
  slli  a0, a0, 1
  ori   a0, a0, 1
  la    t0, tohost
{wait_idle}
{exit_store}
3:
  j     3b

  .section .tohost, "aw", @progbits
  .balign 64
  .globl tohost
tohost:
  .dword 0
  .balign 64
  .globl fromhost
fromhost:
  .dword 0
"""


def _gen_crt0_multicore(design, fp_on, wait_idle, exit_store):
    """crt0 for ``cores.count > 1`` (RV64, Zicsr, a CLINT): the convention in the module docstring."""
    harts = design.cores.count
    msip = design.blocks_of_type("clint")[0].base
    fp_on = fp_on.replace("t0", "t2")  # t0 holds mhartid here
    return f"""{_banner(design, "/*")}
  /* {harts} harts: every hart runs main; hart 0's return is the exit. */
  .section .text.init, "ax", @progbits
  .globl _start
_start:
  .option push
  .option norelax
  la    gp, __global_pointer$
  .option pop
  csrr  t0, mhartid
  li    t1, {harts}
  bgeu  t0, t1, 9f            /* not a hart this design has: park */

  /* sp = _stack_top - mhartid * STACK_SIZE */
  la    sp, _stack_top
  li    t1, {hex(design.program.stack_size)}
  mv    t2, t0
5:
  beqz  t2, 6f
  sub   sp, sp, t1
  addi  t2, t2, -1
  j     5b
6:
{fp_on}  bnez  t0, 7f

  /* Hart 0: zero .bss (8-byte stores; the linker script aligns both ends to 8). */
  la    t0, __bss_start
  la    t1, __bss_end
1:
  bgeu  t0, t1, 2f
  sd    zero, 0(t0)
  addi  t0, t0, 8
  j     1b
2:
  fence rw, rw
  /* ...then release harts 1..{harts - 1}: msip[h] = 1. */
  li    t0, {hex(msip)}
  li    t1, 1
  li    t2, {harts}
  li    t3, 1
8:
  bgeu  t3, t2, 10f
  slli  t4, t3, 2
  add   t4, t0, t4
  sw    t1, 0(t4)
  addi  t3, t3, 1
  j     8b

7:
  /* Hart h > 0: sleep until hart 0 sets msip[h] (mie.MSIE wakes wfi; mstatus.MIE is clear, so no trap). */
  li    t1, 1 << 3
  csrs  mie, t1
  li    t1, {hex(msip)}
  slli  t2, t0, 2
  add   t1, t1, t2
11:
  lw    t2, 0(t1)
  bnez  t2, 12f
  wfi
  j     11b
12:
  sw    zero, 0(t1)
  li    t2, 1 << 3
  csrc  mie, t2
  fence rw, rw

10:
  li    a0, 0
  li    a1, 0
  call  main
  csrr  t0, mhartid
  bnez  t0, 9f              /* only hart 0's return ends the program */

  /* exit(main's return): tohost = (code << 1) | 1. */
  .globl _exit
_exit:
  slli  a0, a0, 1
  ori   a0, a0, 1
  la    t0, tohost
{wait_idle}
{exit_store}
3:
  j     3b

  /* A parked hart: mie is clear, so wfi never wakes (on Naiad and on Spike). */
9:
  csrw  mie, zero
13:
  wfi
  j     13b

  .section .tohost, "aw", @progbits
  .balign 64
  .globl tohost
tohost:
  .dword 0
  .balign 64
  .globl fromhost
fromhost:
  .dword 0
"""


def gen_makefile_vars(design):
    cores = design.cores
    return (
        _banner(design, "#")
        + f"NAIAD_DESIGN_NAME := {design.name}\n"
        + f"NAIAD_XLEN := {cores.xlen}\n"
        + f"NAIAD_MARCH := {cores.march}\n"
        + f"NAIAD_MABI := {cores.mabi}\n"
        + f"NAIAD_CMODEL := {'medany' if cores.xlen == 64 else 'medlow'}\n"
    )


GENERATORS = {
    "naiad.h": gen_header,
    "linker.ld": gen_linker,
    "crt0.S": gen_crt0,
    "naiad.mk": gen_makefile_vars,
}


def generate(design, out_dir):
    """Write every generated file into ``out_dir``; returns their paths."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for filename, gen in GENERATORS.items():
        path = out_dir / filename
        text = gen(design)
        # Leave an unchanged file untouched so make does not rebuild everything.
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
        paths.append(path)
    return paths
