"""Import the Ztt (RISC-V AME) encodings from a spec checkout into ``framework/matrix/ztt_encodings.yaml``.

    tools/naiad/ztt_import.py <riscv-attached-matrix-extension checkout> [-o OUT]

The AME TG's repository (``riscv/riscv-attached-matrix-extension``) generates
``INSTRUCTION_ENCODINGS.md`` from its instruction pages: one table row per
instruction with its format, operand fields, mask and match. This script reads
that table and writes the YAML the Ztt front end (:mod:`framework.matrix.ztt`)
decodes from, recording the checkout's tag and commit, so the simulator pins
one draft and needs no spec checkout at run time. It checks what the table
claims: every operand field lies outside the mask, mask | operand bits covers
the word, and no two instructions' decode patterns overlap.

Exit status: 0 on success, 1 if the table fails a check.
"""

import argparse
import re
import subprocess
import sys
from pathlib import Path

DEFAULT_OUT = (
    Path(__file__).resolve().parents[2] / "framework" / "matrix" / "ztt_encodings.yaml"
)
_ROW = re.compile(
    r"^\|\s*(\d+)\s*\|\s*(R1|R2|R3|Fixed)\s*\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|"
    r"([^|]*)\|([^|]*)\|\s*`(0x[0-9a-f]+)`\s*\|\s*`(0x[0-9a-f]+)`\s*\|\s*$"
)
_FIELD = re.compile(r"`([a-z0-9]+)\[(\d+):(\d+)\]`")


def _git(repo, *args):
    try:
        out = subprocess.run(
            ["git", "-C", str(repo), *args], capture_output=True, text=True, check=True
        )
    except (OSError, subprocess.CalledProcessError):
        return None
    return out.stdout.strip() or None


def parse(text):
    """``[(name, format, mnemonic, {operand: (lo, hi)}, mask, match)]`` from the table's rows."""
    rows = []
    for line in text.splitlines():
        m = _ROW.match(line)
        if not m:
            continue
        _, fmt, name, mnemonic, operands, _fixed, mask, match = m.groups()
        ops = {f: (int(lo), int(hi)) for f, hi, lo in _FIELD.findall(operands)}
        rows.append((name, fmt, mnemonic, ops, int(mask, 16), int(match, 16)))
    return rows


def check(rows):
    """The table's own invariants; returns a list of problems (empty when it is consistent)."""
    bad = []
    names = [r[0] for r in rows]
    if len(set(names)) != len(names):
        bad.append("an instruction name appears twice")
    for name, _fmt, _mn, ops, mask, match in rows:
        op_bits = 0
        for op, (lo, hi) in ops.items():
            bits = ((1 << (hi - lo + 1)) - 1) << lo
            if op_bits & bits:
                bad.append(f"{name}: operand {op} overlaps another operand")
            op_bits |= bits
        if op_bits & mask:
            bad.append(f"{name}: an operand field is inside the mask")
        if (op_bits | mask) != 0xFFFFFFFF:
            bad.append(
                f"{name}: bits {0xFFFFFFFF & ~(op_bits | mask):#010x} are neither fixed nor an operand"
            )
        if match & ~mask:
            bad.append(f"{name}: match has bits outside the mask")
    for i, a in enumerate(rows):
        for b in rows[i + 1 :]:
            if not (a[5] ^ b[5]) & a[4] & b[4]:
                bad.append(f"{a[0]} and {b[0]} overlap")
    return bad


def render(rows, source):
    out = [
        "# Ztt (RISC-V Attached Matrix Extension) encodings, generated by tools/naiad/ztt_import.py",
        "# from the spec repository's INSTRUCTION_ENCODINGS.md. Do not edit by hand: rerun the",
        "# importer against a newer checkout instead. Operands are [lo, hi] bit ranges; every",
        "# other bit is fixed by mask / match.",
        "source:",
        f"  repository: {source['repository']}",
        f"  tag: {source['tag']}",
        f"  commit: {source['commit']}",
        f"  date: {source['date']}",
        "instructions:",
    ]
    for name, fmt, mnemonic, ops, mask, match in rows:
        operands = ", ".join(f"{op}: [{lo}, {hi}]" for op, (lo, hi) in ops.items())
        out.append(
            f'  {name}: {{format: {fmt}, mnemonic: "{mnemonic}", mask: {mask:#010x}, '
            f"match: {match:#010x}, operands: {{{operands}}}}}"
        )
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "spec", type=Path, help="a riscv-attached-matrix-extension checkout"
    )
    ap.add_argument("-o", "--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    table = args.spec / "INSTRUCTION_ENCODINGS.md"
    rows = parse(table.read_text())
    if not rows:
        print(f"{table}: no instruction rows found", file=sys.stderr)
        return 1
    problems = check(rows)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    source = {
        "repository": "riscv/riscv-attached-matrix-extension",
        "tag": _git(args.spec, "describe", "--tags", "--exact-match") or "none",
        "commit": _git(args.spec, "rev-parse", "HEAD") or "unknown",
        "date": _git(args.spec, "log", "-1", "--format=%cs") or "unknown",
    }
    args.out.write_text(render(rows, source))
    print(
        f"{len(rows)} instructions -> {args.out} ({source['tag']}, {source['commit'][:7]})"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
