# ruff: noqa: INP001  (a script next to the variant's sources, not a package)
"""Build, run and check the xDSL-compiled gemm variant against the hand-written AME one.

The ``xdsl`` variant's kernel is assembly that xDSL compiles from a ``linalg.matmul``
(``convert-linalg-to-riscv-ame``, in an xDSL checkout with the ``riscv_ame`` dialect).
It is prebuilt, one ``gemm_<M>x<N>x<K>_<in>_<acc>.S`` per point, so running needs no
xDSL; ``--regen`` recompiles them. The variant is not in the gemm spec's VARIANTS, so
this script adds it before calling :func:`experiments.naiad.dwarfs.run_point`.

Shapes that are not multiples of the 16 x 16 x 16 tile are padded by the lowering: the
full-tile interior reads A, B and C in place, the edges are packed into zero-padded
scratch panels (and C's edges into staging buffers copied back), and a K remainder is
one more reduction step from packed panels. ``run_epilogue.py`` covers the fused
element-wise epilogue.

    python kernels/naiad/dwarfs/gemm/xdsl/run_xdsl.py                 # check + compare
    python kernels/naiad/dwarfs/gemm/xdsl/run_xdsl.py --regen \\
        --xdsl ~/projects/xdsl_2026/xdsl-naiad-matrix                 # recompile first

``--xdsl`` is the xDSL source tree (put on PYTHONPATH); ``--xdsl-python`` the
interpreter that has xDSL's dependencies (default: this one).
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = Path(os.environ.get("WOLFPINE_ROOT", HERE.parents[4]))
sys.path.insert(0, str(REPO))

from experiments.naiad.dwarfs import load_spec, run_point  # noqa: E402

#: (size, in, acc) points with a prebuilt kernel.
POINTS = (
    (32, "fp32", "fp32"),
    (64, "fp32", "fp32"),
    (128, "fp32", "fp32"),
    (64, "bf16", "fp32"),
    (128, "bf16", "fp32"),
    (64, "fp64", "fp64"),
    ((64, 32, 96), "fp32", "fp32"),
    # Ragged shapes: the interior reads in place, the edges are packed and padded.
    (100, "fp32", "fp32"),
    (100, "bf16", "fp32"),
    (100, "fp64", "fp64"),
    ((130, 70, 33), "fp32", "fp32"),
    ((36, 40, 50), "fp32", "fp32"),
    ((64, 64, 72), "fp32", "fp32"),
    ((17, 300, 41), "bf16", "fp32"),
)

MLIR_TYPES = {"fp64": "f64", "fp32": "f32", "fp16": "f16", "bf16": "bf16"}

#: The design's unit: 16x16x16, 8 tiles, 4 accumulators (naiad-dwarfs.yaml).
PIPELINE = ",".join(
    [
        "convert-linalg-to-riscv-ame{m=16 n=16 k=16 tiles=8 accs=4}",
        "convert-func-to-riscv-func",
        "reconcile-unrealized-casts",
        "canonicalize",
        "riscv-ame-allocate-registers{tiles=8 accs=4}",
        "riscv-lower-parallel-mov",
        "canonicalize",
        "lower-riscv-scf-to-labels",
    ]
)


def dims(size):
    return tuple(size) if isinstance(size, tuple) else (size, size, size)


def asm_name(size, in_fmt, acc_fmt):
    m, n, k = dims(size)
    return f"gemm_{m}x{n}x{k}_{in_fmt}_{acc_fmt}.S"


def mlir(size, in_fmt, acc_fmt):
    m, n, k = dims(size)
    ti, ta = MLIR_TYPES[in_fmt], MLIR_TYPES[acc_fmt]
    a, b, c = f"memref<{m}x{k}x{ti}>", f"memref<{k}x{n}x{ti}>", f"memref<{m}x{n}x{ta}>"
    return f"""func.func @gemm_xdsl(%A: {a}, %B: {b}, %C: {c}) {{
  %zero = arith.constant 0.0 : {ta}
  linalg.fill ins(%zero : {ta}) outs(%C : {c})
  linalg.matmul ins(%A, %B : {a}, {b}) outs(%C : {c})
  func.return
}}
"""


def compile_mlir(text, xdsl, python):
    """Assembly for the MLIR `text`, compiled by the xDSL tree `xdsl` with `python`."""
    env = dict(os.environ, PYTHONPATH=str(Path(xdsl).resolve()))
    done = subprocess.run(
        [python, "-m", "xdsl.tools.xdsl_opt", "-p", PIPELINE, "-t", "riscv-asm"],
        input=text,
        capture_output=True,
        text=True,
        env=env,
    )
    if done.returncode != 0:
        sys.exit(f"xdsl-opt failed:\n{done.stderr}")
    out = done.stdout
    if "_ame_buf" in out:
        # Back to .text after the kernel's data: it is .include'd into a C file,
        # and the compiler's own code follows it.
        out += ".text\n"
    return out


def regen(xdsl, python):
    for size, in_fmt, acc_fmt in POINTS:
        out = compile_mlir(mlir(size, in_fmt, acc_fmt), xdsl, python)
        header = (
            f"# Generated by xDSL (convert-linalg-to-riscv-ame) from linalg.matmul\n"
            f"# {dims(size)} {in_fmt} -> {acc_fmt}; regenerate with run_xdsl.py --regen.\n"
        )
        (HERE / asm_name(size, in_fmt, acc_fmt)).write_text(header + out)
        print(f"wrote {asm_name(size, in_fmt, acc_fmt)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--regen", action="store_true", help="recompile the kernels with xDSL first"
    )
    ap.add_argument(
        "--xdsl", default=os.environ.get("XDSL_SRC"), help="xDSL source tree"
    )
    ap.add_argument("--xdsl-python", default=sys.executable)
    ap.add_argument(
        "--dwarfs-root", default=None, help="a copy of kernels/naiad/dwarfs to run from"
    )
    ap.add_argument("--only", nargs="*", help="sizes to run, e.g. 64x64x64 130x70x33")
    args = ap.parse_args()
    if args.regen:
        if not args.xdsl:
            ap.error("--regen needs --xdsl (or XDSL_SRC)")
        regen(args.xdsl, args.xdsl_python)

    spec = load_spec("gemm", args.dwarfs_root)
    spec.VARIANTS["xdsl"] = "xdsl"
    ok = True
    print(
        f"{'size':>12} {'formats':>11} {'xdsl':>8} {'ame':>8} {'ratio':>6}  check (normwise)"
    )
    for size, in_fmt, acc_fmt in POINTS:
        if args.only and "x".join(map(str, dims(size))) not in args.only:
            continue
        res = {v: run_point(spec, v, size, in_fmt, acc_fmt) for v in ("xdsl", "ame")}
        x, h = res["xdsl"], res["ame"]
        ok &= x.passed
        err = x.error.get("C", {}).get("normwise", float("nan"))
        print(
            f"{'x'.join(map(str, dims(size))):>12} {in_fmt + '/' + acc_fmt:>11} "
            f"{x.region_cycles:>8} {h.region_cycles:>8} {x.region_cycles / h.region_cycles:>6.3f}  "
            f"{'pass' if x.passed else 'FAIL'} ({err:.2e})"
        )
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
