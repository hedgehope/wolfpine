# ruff: noqa: INP001  (a script next to the variant's sources, not a package)
"""Build, run and check xDSL's fused matmul epilogue against the unfused one, on Naiad.

The kernels are a ``linalg.matmul`` followed by an element-wise ``linalg.generic``
on its result (``D = C * rsqrt(Y)``, or ``D = max(0.5 C + Y, 0)``), compiled by
xDSL's ``convert-linalg-to-riscv-ame``, which fuses the generic into the matmul's
accumulators with the custom-3 element-wise instructions (``aew.*``, ``aewu``). The
unfused baseline is the plain xDSL matmul (``gemm_<M>x<N>x<K>_fp32_fp32.S`` from this
directory) followed by the same epilogue as a C loop on the scalar core.

The fused kernels need the matrix unit's ``ewise`` and ``ewise_tx`` features, which
``naiad-dwarfs.yaml`` does not list, so this script writes a copy of it with the
epilogue sweep's feature list (kernels/naiad/build/xdsl/naiad-dwarfs-ewise.yaml) and
runs both variants against it. The kernels are prebuilt; ``--regen`` recompiles the
fused ones (the unfused ones are run_xdsl.py's).

    python kernels/naiad/dwarfs/gemm/xdsl/run_epilogue.py
    python kernels/naiad/dwarfs/gemm/xdsl/run_epilogue.py --regen \\
        --xdsl ~/projects/xdsl_2026/xdsl-naiad-matrix
"""

import argparse
import os
import sys
import types
from pathlib import Path

import numpy as np
import yaml

HERE = Path(__file__).resolve().parent
REPO = Path(os.environ.get("WOLFPINE_ROOT", HERE.parents[4]))
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(HERE))

from experiments.naiad.dwarfs import (  # noqa: E402
    DEFAULT_DESIGN,
    KERNELS,
    load_spec,
    run_point,
)

#: Epilogue name -> (the generic's body, the golden D from C = A . B and Y).
EPILOGUES = {
    "rsqrt": (
        """    %r = math.rsqrt %y : f32
    %d = arith.mulf %c, %r : f32""",
        lambda c, y: c / np.sqrt(y),
    ),
    "relu": (
        """    %half = arith.constant 0.5 : f32
    %floor = arith.constant 0.0 : f32
    %s = arith.mulf %c, %half : f32
    %b = arith.addf %s, %y : f32
    %d = arith.maximumf %b, %floor : f32""",
        lambda c, y: np.maximum(0.5 * c + y, 0.0),
    ),
}
SIZES = (64, 128)
FEATURES = [
    "transpose",
    "shift",
    "epilogue",
    "semiring",
    "acc_move",
    "convert",
    "ewise",
    "ewise_tx",
]


def asm_name(epi, n):
    return f"gemm_{epi}_{n}x{n}x{n}_fp32_fp32"


def mlir(epi, n):
    t = f"memref<{n}x{n}xf32>"
    ident = "affine_map<(i, j) -> (i, j)>"
    return f"""func.func @gemm_epilogue_xdsl(%A: {t}, %B: {t}, %C: {t}, %Y: {t}) {{
  %zero = arith.constant 0.0 : f32
  linalg.fill ins(%zero : f32) outs(%C : {t})
  linalg.matmul ins(%A, %B : {t}, {t}) outs(%C : {t})
  linalg.generic {{
    indexing_maps = [{ident}, {ident}, {ident}],
    iterator_types = ["parallel", "parallel"]
  }} ins(%C, %Y : {t}, {t}) outs(%C : {t}) {{
  ^bb0(%c: f32, %y: f32, %o: f32):
{EPILOGUES[epi][0]}
    linalg.yield %d : f32
  }}
  func.return
}}
"""


def regen(xdsl, python):
    from run_xdsl import compile_mlir

    for epi in EPILOGUES:
        for n in SIZES:
            header = (
                "# Generated by xDSL (convert-linalg-to-riscv-ame) from a linalg.matmul\n"
                f"# with a fused {epi} epilogue, {n}^3 fp32; regenerate with "
                "run_epilogue.py --regen.\n"
            )
            out = compile_mlir(mlir(epi, n), xdsl, python)
            (HERE / "epilogue" / f"{asm_name(epi, n)}.S").write_text(header + out)
            print(f"wrote epilogue/{asm_name(epi, n)}.S")


def ewise_design():
    data = yaml.safe_load(Path(DEFAULT_DESIGN).read_text())
    data["name"] = "naiad-dwarfs-ewise"
    data["matrix"]["features"] = FEATURES
    out = KERNELS / "build" / "xdsl" / "naiad-dwarfs-ewise.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(data, sort_keys=False)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return out


def epilogue_spec(gemm, epi):
    """The gemm spec with Y as an input and D = f(A . B, Y) as the result."""
    spec = types.ModuleType(f"gemm_{epi}")
    spec.__dict__.update(
        {k: v for k, v in vars(gemm).items() if not k.startswith("__")}
    )
    spec.__file__ = gemm.__file__  # sources are found next to the gemm spec
    spec.VARIANTS = {"xdsl_epi": "xdsl/epilogue"}
    f = EPILOGUES[epi][1]

    def make_inputs(size, rng):
        inputs = gemm.make_inputs(size, rng)
        m, n, _ = gemm.dims(size)
        # rsqrt needs Y > 0; the ReLU's bias straddles zero.
        y = rng.random((m, n)) + 0.5 if epi == "rsqrt" else rng.standard_normal((m, n))
        return {**inputs, "Y": y}

    def encode(inputs, in_fmt, acc_fmt):
        return {
            **gemm.encode(inputs, in_fmt, acc_fmt),
            "Y": np.ascontiguousarray(inputs["Y"], np.float32),
        }

    def golden(inputs):
        return {"C": f(inputs["A"] @ inputs["B"], inputs["Y"])}

    spec.make_inputs, spec.encode, spec.golden = make_inputs, encode, golden
    return spec


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--regen", action="store_true", help="recompile the fused kernels")
    ap.add_argument(
        "--xdsl", default=os.environ.get("XDSL_SRC"), help="xDSL source tree"
    )
    ap.add_argument("--xdsl-python", default=sys.executable)
    ap.add_argument(
        "--dwarfs-root", default=None, help="a copy of kernels/naiad/dwarfs to run from"
    )
    args = ap.parse_args()
    if args.regen:
        if not args.xdsl:
            ap.error("--regen needs --xdsl (or XDSL_SRC)")
        regen(args.xdsl, args.xdsl_python)

    gemm = load_spec("gemm", args.dwarfs_root)
    design = ewise_design()
    ok = True
    print(
        f"{'size':>5} {'epilogue':>8} {'fused':>8} {'unfused':>8} {'ratio':>6}  check"
    )
    for epi in EPILOGUES:
        spec = epilogue_spec(gemm, epi)
        for n in SIZES:
            res = {}
            for fused in (1, 0):
                kernel = asm_name(epi, n) if fused else f"../gemm_{n}x{n}x{n}_fp32_fp32"
                flags = [
                    f"-DXDSL_ASM={kernel}",
                    f"-DXDSL_FUSED={fused}",
                    f"-DXDSL_EPI_RSQRT={int(epi == 'rsqrt')}",
                ]
                res[fused] = run_point(
                    spec, "xdsl_epi", n, "fp32", "fp32", design, extra_cflags=flags
                )
            x, u = res[1], res[0]
            ok &= x.passed and u.passed
            err = x.error.get("C", {}).get("normwise", float("nan"))
            print(
                f"{n:>5} {epi:>8} {x.region_cycles:>8} {u.region_cycles:>8} "
                f"{x.region_cycles / u.region_cycles:>6.3f}  "
                f"{'pass' if x.passed else 'FAIL'} ({err:.2e})"
                f"{'' if u.passed else ' (unfused FAIL)'}"
            )
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
