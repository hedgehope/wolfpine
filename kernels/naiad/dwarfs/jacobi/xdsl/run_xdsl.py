# ruff: noqa: INP001  (a script next to the variant's sources, not a package)
"""Build, run and check the xDSL-compiled jacobi variant against the hand-written AME one.

The ``xdsl`` variant's kernel is one sweep of assembly that xDSL compiles from the
5-point stencil written as a ``linalg.generic`` over four shifted ``memref.subview``s
of the grid, ``0.25 * ((up + down) + (left + right))``, lowered by
``convert-linalg-to-riscv-ame`` (its linear-combination pattern) in an xDSL checkout
with the ``riscv_ame`` dialect. It is prebuilt, one ``jacobi_<N>_<in>_<acc>.S`` per
point, so running needs no xDSL; ``--regen`` recompiles them. The variant is not in the
jacobi spec's VARIANTS, so this script adds it before calling
:func:`experiments.naiad.dwarfs.run_point`, and passes the kernel's name as
``-DXDSL_ASM``. The lowering produces the ame variant's window form, so the table also
shows ``ame`` with ``form="window"`` beside the default banded form.

    python kernels/naiad/dwarfs/jacobi/xdsl/run_xdsl.py                 # check + compare
    python kernels/naiad/dwarfs/jacobi/xdsl/run_xdsl.py --regen \\
        --xdsl ~/projects/xdsl_2026/xdsl-naiad-matrix                   # recompile first

``--xdsl`` is the xDSL source tree (put on PYTHONPATH); ``--xdsl-python`` the
interpreter that has xDSL's dependencies (default: this one).
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = Path(os.environ.get("WOLFPINE_ROOT", HERE.parents[4]))
sys.path.insert(0, str(REPO))

from experiments.naiad.dwarfs import load_spec, run_point  # noqa: E402

#: (n, in, acc) points with a prebuilt kernel (same-format pairs only).
POINTS = (
    (34, "fp32", "fp32"),
    (66, "fp32", "fp32"),
    (130, "fp32", "fp32"),
    (66, "fp64", "fp64"),
)

MLIR_TYPES = {"fp64": "f64", "fp32": "f32", "fp16": "f16", "bf16": "bf16"}

#: The design's unit: 16x16x16, 8 tiles, 4 accumulators (naiad-dwarfs.yaml).
PIPELINE = ",".join(
    [
        "convert-linalg-to-riscv-ame{m=16 n=16 k=16 tiles=8 accs=4}",
        "convert-func-to-riscv-func",
        "reconcile-unrealized-casts",
        "canonicalize",
        "riscv-ame-allocate-registers{tiles=8 accs=4}",
        "riscv-lower-parallel-mov",
        "canonicalize",
        "lower-riscv-scf-to-labels",
    ]
)


def asm_name(n, in_fmt, acc_fmt):
    return f"jacobi_{n}_{in_fmt}_{acc_fmt}"


def mlir(n, in_fmt, acc_fmt):
    t = MLIR_TYPES[in_fmt]
    assert t == MLIR_TYPES[acc_fmt], "same-format pairs only"
    grid, m = f"memref<{n}x{n}x{t}>", n - 2

    def view(name, src, row, col):
        ty = f"memref<{m}x{m}x{t}, strided<[{n}, 1], offset: {row * n + col}>>"
        op = f"%{name} = memref.subview %{src}[{row}, {col}] [{m}, {m}] [1, 1]"
        return f"  {op} : {grid} to {ty}", ty

    views = [view("up", "u", 0, 1), view("dn", "u", 2, 1), view("lt", "u", 1, 0)]
    views += [view("rt", "u", 1, 2), view("out", "v", 1, 1)]
    decls = "\n".join(v[0] for v in views)
    ins = ", ".join(v[1] for v in views[:4])
    ident = "affine_map<(i, j) -> (i, j)>"
    return f"""func.func @jacobi_xdsl(%u: {grid}, %v: {grid}) {{
{decls}
  linalg.generic {{
    indexing_maps = [{", ".join([ident] * 5)}],
    iterator_types = ["parallel", "parallel"]
  }} ins(%up, %dn, %lt, %rt : {ins}) outs(%out : {views[4][1]}) {{
  ^bb0(%a: {t}, %b: {t}, %c: {t}, %d: {t}, %o: {t}):
    %vert = arith.addf %a, %b : {t}
    %horiz = arith.addf %c, %d : {t}
    %sum = arith.addf %vert, %horiz : {t}
    %quarter = arith.constant 0.25 : {t}
    %r = arith.mulf %sum, %quarter : {t}
    linalg.yield %r : {t}
  }}
  func.return
}}
"""


def compile_mlir(text, xdsl, python):
    env = dict(os.environ, PYTHONPATH=str(Path(xdsl).resolve()))
    done = subprocess.run(
        [python, "-m", "xdsl.tools.xdsl_opt", "-p", PIPELINE, "-t", "riscv-asm"],
        input=text,
        capture_output=True,
        text=True,
        env=env,
    )
    if done.returncode != 0:
        sys.exit(f"xdsl-opt failed:\n{done.stderr}")
    out = done.stdout
    if "_ame_buf" in out:
        # Back to .text after the kernel's data: it is .include'd into a C file,
        # and the compiler's own code follows it.
        out += ".text\n"
    return out


def regen(xdsl, python):
    for n, in_fmt, acc_fmt in POINTS:
        header = (
            "# Generated by xDSL (convert-linalg-to-riscv-ame) from a linalg stencil;\n"
            f"# n = {n}, {in_fmt} -> {acc_fmt}; regenerate with run_xdsl.py --regen.\n"
        )
        out = compile_mlir(mlir(n, in_fmt, acc_fmt), xdsl, python)
        (HERE / f"{asm_name(n, in_fmt, acc_fmt)}.S").write_text(header + out)
        print(f"wrote {asm_name(n, in_fmt, acc_fmt)}.S")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--regen", action="store_true", help="recompile the kernels with xDSL first"
    )
    ap.add_argument(
        "--xdsl", default=os.environ.get("XDSL_SRC"), help="xDSL source tree"
    )
    ap.add_argument("--xdsl-python", default=sys.executable)
    ap.add_argument(
        "--dwarfs-root", default=None, help="a copy of kernels/naiad/dwarfs to run from"
    )
    args = ap.parse_args()
    if args.regen:
        if not args.xdsl:
            ap.error("--regen needs --xdsl (or XDSL_SRC)")
        regen(args.xdsl, args.xdsl_python)

    spec = load_spec("jacobi", args.dwarfs_root)
    spec.VARIANTS["xdsl"] = "xdsl"
    window = spec.switch_cflags({"form": "window"})
    ok = True
    print(
        f"{'n':>5} {'formats':>11} {'xdsl':>8} {'ame':>8} {'ratio':>6} "
        f"{'window':>8} {'ratio':>6}  check (normwise)"
    )
    for n, in_fmt, acc_fmt in POINTS:
        flags = [f"-DXDSL_ASM={asm_name(n, in_fmt, acc_fmt)}"]
        x = run_point(spec, "xdsl", n, in_fmt, acc_fmt, extra_cflags=flags)
        h = run_point(spec, "ame", n, in_fmt, acc_fmt)
        w = run_point(spec, "ame", n, in_fmt, acc_fmt, extra_cflags=window)
        ok &= x.passed
        err = x.error.get("out", {}).get("normwise", float("nan"))
        print(
            f"{n:>5} {in_fmt + '/' + acc_fmt:>11} {x.region_cycles:>8} "
            f"{h.region_cycles:>8} {x.region_cycles / h.region_cycles:>6.3f} "
            f"{w.region_cycles:>8} {x.region_cycles / w.region_cycles:>6.3f}  "
            f"{'pass' if x.passed else 'FAIL'} ({err:.2e})"
        )
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
