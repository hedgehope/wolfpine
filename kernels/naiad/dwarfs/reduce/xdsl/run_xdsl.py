# ruff: noqa: INP001  (a script next to the variant's sources, not a package)
"""Build, run and check the xDSL-compiled reduce variant against the hand-written AME one.

The ``xdsl`` variant's kernel is assembly that xDSL compiles from a ``linalg.reduce``
(fp32, fp64) or a ``linalg.generic`` sum with a widening ``arith.extf`` (bf16, fp16
inputs into an fp32 sum), lowered by ``convert-linalg-to-riscv-ame`` in an xDSL
checkout with the ``riscv_ame`` dialect. It is prebuilt, one
``reduce_<N>_<in>_<acc>.S`` per point, so running needs no xDSL; ``--regen``
recompiles them. The variant is not in the reduce spec's VARIANTS, so this script
adds it before calling :func:`framework.naiad.dwarfs.run_point`, and passes the
kernel's name as ``-DXDSL_ASM``.

A ragged size (not a multiple of 1024, which the spec and the ame variant require)
runs the xdsl variant only, with the spec's size check relaxed for it.

    python kernels/naiad/dwarfs/reduce/xdsl/run_xdsl.py                 # check + compare
    python kernels/naiad/dwarfs/reduce/xdsl/run_xdsl.py --regen \\
        --xdsl ~/projects/xdsl_2026/xdsl-naiad-matrix                   # recompile first

``--xdsl`` is the xDSL source tree (put on PYTHONPATH); ``--xdsl-python`` the
interpreter that has xDSL's dependencies (default: this one).
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = Path(os.environ.get("WOLFPINE_ROOT", HERE.parents[4]))
sys.path.insert(0, str(REPO))

from framework.naiad.dwarfs import load_spec, run_point  # noqa: E402

#: (size, in, acc) points with a prebuilt kernel; ragged sizes run xdsl only.
POINTS = (
    (4096, "fp32", "fp32"),
    (16384, "fp32", "fp32"),
    (65536, "fp32", "fp32"),
    (16384, "fp64", "fp64"),
    (16384, "bf16", "fp32"),
    (16384, "fp16", "fp32"),
    (10000, "fp32", "fp32"),
)

MLIR_TYPES = {"fp64": "f64", "fp32": "f32", "fp16": "f16", "bf16": "bf16"}

#: The design's unit: 16x16x16, 8 tiles, 4 accumulators (naiad-dwarfs.yaml).
PIPELINE = ",".join(
    [
        "convert-linalg-to-riscv-ame{m=16 n=16 k=16 tiles=8 accs=4}",
        "convert-func-to-riscv-func",
        "reconcile-unrealized-casts",
        "canonicalize",
        "riscv-ame-allocate-registers{tiles=8 accs=4}",
        "riscv-lower-parallel-mov",
        "canonicalize",
        "lower-riscv-scf-to-labels",
    ]
)


def asm_name(n, in_fmt, acc_fmt):
    return f"reduce_{n}_{in_fmt}_{acc_fmt}"


def mlir(n, in_fmt, acc_fmt):
    ti, ta = MLIR_TYPES[in_fmt], MLIR_TYPES[acc_fmt]
    x, r = f"memref<{n}x{ti}>", f"memref<{ta}>"
    if ti == ta:
        body = f"""  linalg.reduce ins(%x : {x}) outs(%r : {r}) dimensions = [0]
    (%in: {ti}, %acc: {ta}) {{
      %s = arith.addf %in, %acc : {ta}
      linalg.yield %s : {ta}
    }}"""
    else:
        body = f"""  linalg.generic {{
    indexing_maps = [affine_map<(i) -> (i)>, affine_map<(i) -> ()>],
    iterator_types = ["reduction"]
  }} ins(%x : {x}) outs(%r : {r}) {{
  ^bb0(%in: {ti}, %acc: {ta}):
    %w = arith.extf %in : {ti} to {ta}
    %s = arith.addf %w, %acc : {ta}
    linalg.yield %s : {ta}
  }}"""
    return f"""func.func @reduce_xdsl(%x: {x}, %r: {r}) {{
  %zero = arith.constant 0.0 : {ta}
  linalg.fill ins(%zero : {ta}) outs(%r : {r})
{body}
  func.return
}}
"""


def compile_mlir(text, xdsl, python):
    env = dict(os.environ, PYTHONPATH=str(Path(xdsl).resolve()))
    done = subprocess.run(
        [python, "-m", "xdsl.tools.xdsl_opt", "-p", PIPELINE, "-t", "riscv-asm"],
        input=text,
        capture_output=True,
        text=True,
        env=env,
    )
    if done.returncode != 0:
        sys.exit(f"xdsl-opt failed:\n{done.stderr}")
    out = done.stdout
    if "_ame_buf" in out:
        # Back to .text after the kernel's data: it is .include'd into a C file,
        # and the compiler's own code follows it.
        out += ".text\n"
    return out


def regen(xdsl, python):
    for n, in_fmt, acc_fmt in POINTS:
        header = (
            "# Generated by xDSL (convert-linalg-to-riscv-ame) from a linalg sum;\n"
            f"# n = {n}, {in_fmt} -> {acc_fmt}; regenerate with run_xdsl.py --regen.\n"
        )
        out = compile_mlir(mlir(n, in_fmt, acc_fmt), xdsl, python)
        (HERE / f"{asm_name(n, in_fmt, acc_fmt)}.S").write_text(header + out)
        print(f"wrote {asm_name(n, in_fmt, acc_fmt)}.S")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--regen", action="store_true", help="recompile the kernels with xDSL first"
    )
    ap.add_argument(
        "--xdsl", default=os.environ.get("XDSL_SRC"), help="xDSL source tree"
    )
    ap.add_argument("--xdsl-python", default=sys.executable)
    ap.add_argument(
        "--dwarfs-root", default=None, help="a copy of kernels/naiad/dwarfs to run from"
    )
    args = ap.parse_args()
    if args.regen:
        if not args.xdsl:
            ap.error("--regen needs --xdsl (or XDSL_SRC)")
        regen(args.xdsl, args.xdsl_python)

    spec = load_spec("reduce", args.dwarfs_root)
    spec.VARIANTS["xdsl"] = "xdsl"
    check_size = spec._check_size
    ok = True
    print(
        f"{'n':>8} {'formats':>11} {'xdsl':>8} {'ame':>8} {'ratio':>6}  check (normwise)"
    )
    for n, in_fmt, acc_fmt in POINTS:
        ragged = n % 1024 != 0
        spec._check_size = (lambda n: None) if ragged else check_size
        flags = [f"-DXDSL_ASM={asm_name(n, in_fmt, acc_fmt)}"]
        x = run_point(spec, "xdsl", n, in_fmt, acc_fmt, extra_cflags=flags)
        h = None if ragged else run_point(spec, "ame", n, in_fmt, acc_fmt)
        ok &= x.passed
        err = x.error.get("sum", {}).get("normwise", float("nan"))
        hc = f"{h.region_cycles:>8}" if h else f"{'-':>8}"
        ratio = f"{x.region_cycles / h.region_cycles:>6.3f}" if h else f"{'-':>6}"
        print(
            f"{n:>8} {in_fmt + '/' + acc_fmt:>11} {x.region_cycles:>8} {hc} {ratio}  "
            f"{'pass' if x.passed else 'FAIL'} ({err:.2e})"
        )
    spec._check_size = check_size
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
