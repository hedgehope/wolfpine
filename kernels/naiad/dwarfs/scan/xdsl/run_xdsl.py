# ruff: noqa: INP001  (a script next to the variant's sources, not a package)
"""Build, run and check the xDSL-compiled scan variant against the hand-written AME one.

The ``xdsl`` variant's kernel is assembly that xDSL compiles from the scan's definition
as a ``linalg.generic``, the masked triangular sum ``y[i] = sum_k (k <= i ? x[k] : 0)``
(the mask from ``linalg.index``; a widening ``arith.extf`` for 16-bit inputs), lowered
by ``convert-linalg-to-riscv-ame`` in an xDSL checkout with the ``riscv_ame`` dialect to
the ame variant's triangular-tile form. It is prebuilt, one ``scan_<N>_<in>_<acc>.S``
per point, so running needs no xDSL; ``--regen`` recompiles them. The variant is not in
the scan spec's VARIANTS, so this script adds it before calling
:func:`framework.naiad.dwarfs.run_point`, and passes the kernel's name as
``-DXDSL_ASM``.

A ragged size (not a multiple of 256, which the spec and the ame variant require) runs
the xdsl variant only, with the spec's size check relaxed for it.

    python kernels/naiad/dwarfs/scan/xdsl/run_xdsl.py                 # check + compare
    python kernels/naiad/dwarfs/scan/xdsl/run_xdsl.py --regen \\
        --xdsl ~/projects/xdsl_2026/xdsl-naiad-matrix                 # recompile first

``--xdsl`` is the xDSL source tree (put on PYTHONPATH); ``--xdsl-python`` the
interpreter that has xDSL's dependencies (default: this one).
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = Path(os.environ.get("WOLFPINE_ROOT", HERE.parents[4]))
sys.path.insert(0, str(REPO))

from framework.naiad.dwarfs import load_spec, run_point  # noqa: E402

#: (size, in, acc) points with a prebuilt kernel; ragged sizes run xdsl only.
POINTS = (
    (4096, "fp32", "fp32"),
    (16384, "fp32", "fp32"),
    (65536, "fp32", "fp32"),
    (16384, "fp64", "fp64"),
    (16384, "bf16", "fp32"),
    (16384, "fp16", "fp32"),
    (10000, "fp32", "fp32"),
)

MLIR_TYPES = {"fp64": "f64", "fp32": "f32", "fp16": "f16", "bf16": "bf16"}

#: The design's unit: 16x16x16, 8 tiles, 4 accumulators (naiad-dwarfs.yaml).
PIPELINE = ",".join(
    [
        "convert-linalg-to-riscv-ame{m=16 n=16 k=16 tiles=8 accs=4}",
        "convert-func-to-riscv-func",
        "reconcile-unrealized-casts",
        "canonicalize",
        "riscv-ame-allocate-registers{tiles=8 accs=4}",
        "riscv-lower-parallel-mov",
        "canonicalize",
        "lower-riscv-scf-to-labels",
    ]
)


def asm_name(n, in_fmt, acc_fmt):
    return f"scan_{n}_{in_fmt}_{acc_fmt}"


def mlir(n, in_fmt, acc_fmt):
    ti, ta = MLIR_TYPES[in_fmt], MLIR_TYPES[acc_fmt]
    x, y = f"memref<{n}x{ti}>", f"memref<{n}x{ta}>"
    widen = "" if ti == ta else f"\n    %in = arith.extf %x_k : {ti} to {ta}"
    value = "%x_k" if ti == ta else "%in"
    return f"""func.func @scan_xdsl(%x: {x}, %y: {y}) {{
  %zero = arith.constant 0.0 : {ta}
  linalg.fill ins(%zero : {ta}) outs(%y : {y})
  linalg.generic {{
    indexing_maps = [affine_map<(i, k) -> (k)>, affine_map<(i, k) -> (i)>],
    iterator_types = ["parallel", "reduction"]
  }} ins(%x : {x}) outs(%y : {y}) {{
  ^bb0(%x_k: {ti}, %acc: {ta}):{widen}
    %i = linalg.index 0 : index
    %k = linalg.index 1 : index
    %le = arith.cmpi ule, %k, %i : index
    %z = arith.constant 0.0 : {ta}
    %v = arith.select %le, {value}, %z : {ta}
    %s = arith.addf %v, %acc : {ta}
    linalg.yield %s : {ta}
  }}
  func.return
}}
"""


def compile_mlir(text, xdsl, python):
    env = dict(os.environ, PYTHONPATH=str(Path(xdsl).resolve()))
    done = subprocess.run(
        [python, "-m", "xdsl.tools.xdsl_opt", "-p", PIPELINE, "-t", "riscv-asm"],
        input=text,
        capture_output=True,
        text=True,
        env=env,
    )
    if done.returncode != 0:
        sys.exit(f"xdsl-opt failed:\n{done.stderr}")
    out = done.stdout
    if "_ame_buf" in out:
        # Back to .text after the kernel's data: it is .include'd into a C file,
        # and the compiler's own code follows it.
        out += ".text\n"
    return out


def regen(xdsl, python):
    for n, in_fmt, acc_fmt in POINTS:
        header = (
            "# Generated by xDSL (convert-linalg-to-riscv-ame) from a linalg scan;\n"
            f"# n = {n}, {in_fmt} -> {acc_fmt}; regenerate with run_xdsl.py --regen.\n"
        )
        out = compile_mlir(mlir(n, in_fmt, acc_fmt), xdsl, python)
        (HERE / f"{asm_name(n, in_fmt, acc_fmt)}.S").write_text(header + out)
        print(f"wrote {asm_name(n, in_fmt, acc_fmt)}.S")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--regen", action="store_true", help="recompile the kernels with xDSL first"
    )
    ap.add_argument(
        "--xdsl", default=os.environ.get("XDSL_SRC"), help="xDSL source tree"
    )
    ap.add_argument("--xdsl-python", default=sys.executable)
    ap.add_argument(
        "--dwarfs-root", default=None, help="a copy of kernels/naiad/dwarfs to run from"
    )
    args = ap.parse_args()
    if args.regen:
        if not args.xdsl:
            ap.error("--regen needs --xdsl (or XDSL_SRC)")
        regen(args.xdsl, args.xdsl_python)

    spec = load_spec("scan", args.dwarfs_root)
    spec.VARIANTS["xdsl"] = "xdsl"
    check_size = spec._check_size
    ok = True
    print(
        f"{'n':>8} {'formats':>11} {'xdsl':>8} {'ame':>8} {'ratio':>6}  check (normwise)"
    )
    for n, in_fmt, acc_fmt in POINTS:
        ragged = n % 256 != 0
        spec._check_size = (lambda n: None) if ragged else check_size
        flags = [f"-DXDSL_ASM={asm_name(n, in_fmt, acc_fmt)}"]
        x = run_point(spec, "xdsl", n, in_fmt, acc_fmt, extra_cflags=flags)
        h = None if ragged else run_point(spec, "ame", n, in_fmt, acc_fmt)
        ok &= x.passed
        err = x.error.get("y", {}).get("normwise", float("nan"))
        hc = f"{h.region_cycles:>8}" if h else f"{'-':>8}"
        ratio = f"{x.region_cycles / h.region_cycles:>6.3f}" if h else f"{'-':>6}"
        print(
            f"{n:>8} {in_fmt + '/' + acc_fmt:>11} {x.region_cycles:>8} {hc} {ratio}  "
            f"{'pass' if x.passed else 'FAIL'} ({err:.2e})"
        )
    spec._check_size = check_size
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
